#!/usr/bin/env python3
"""Build the timezone-to-landing-camera table the global map reads.

Writes apps/shared/data/tz-home.js, a classic script that sets
window.POW_TZ_HOME = {zones, cameras}:

  zones    IANA zone name -> project country code (every zone in the
           system zone table whose country is in the world registry)
  cameras  project country code -> [lng, lat, zoom]: the country page's
           own landing camera where a page exists (apps/regions/<cc>/
           index.html, REGION_CONFIG.center and initialZoom), otherwise
           the registry camera (apps/shared/data/country-registry.json)

The global map (apps/global/index.html) loads the table synchronously and
opens on the visitor's own country, named by the device timezone without
any permission prompt; an unknown zone leaves the page's default camera.
Rerun when a country page launches or changes its camera, or after a
registry rebuild. The zone table is the IANA tz database's zone.tab
(public domain); the first readable path below is used.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
REGISTRY = REPO / "apps/shared/data/country-registry.json"
PAGES = REPO / "apps/regions"
OUT = REPO / "apps/shared/data/tz-home.js"
ZONE_TABS = [
    Path("/usr/share/zoneinfo/zone1970.tab"),
    Path("/usr/share/zoneinfo/zone.tab"),
    Path("/var/db/timezone/zoneinfo/zone1970.tab"),
    Path("/var/db/timezone/zoneinfo/zone.tab"),
]
# project page codes where they differ from iso alpha-2
PROJECT_CODE_FOR_ISO = {"gb": "uk"}
CENTER_RE = re.compile(r"center:\s*\[\s*(-?\d+(?:\.\d+)?)\s*,\s*(-?\d+(?:\.\d+)?)\s*\]")
ZOOM_RE = re.compile(r"initialZoom:\s*(\d+(?:\.\d+)?)")


def zone_tab_path(candidates=ZONE_TABS):
    for tab in candidates:
        if tab.is_file():
            return tab
    try:
        import tzdata  # type: ignore

        base = Path(tzdata.__file__).resolve().parent / "zoneinfo"
        for name in ("zone1970.tab", "zone.tab"):
            if (base / name).is_file():
                return base / name
    except ImportError:
        pass
    sys.exit("no zone table found (zone1970.tab or zone.tab); install tzdata")


def parse_zone_tab(text):
    """Zone name -> lower-case iso alpha-2 of the zone's first listed country."""
    zones = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3:
            continue
        primary = fields[0].split(",")[0].strip().lower()
        if len(primary) == 2:
            zones.setdefault(fields[2].strip(), primary)
    return zones


def page_camera(html):
    """[lng, lat, zoom] from a country page's REGION_CONFIG, or None."""
    centre = CENTER_RE.search(html)
    zoom = ZOOM_RE.search(html)
    if not centre or not zoom:
        return None
    return [float(centre.group(1)), float(centre.group(2)), float(zoom.group(1))]


def build(registry, zones, pages_dir=PAGES):
    cameras = {}
    for entry in registry["countries"]:
        code = entry["code"]
        camera = None
        page = pages_dir / code / "index.html"
        if entry.get("page") and page.is_file():
            camera = page_camera(page.read_text(encoding="utf-8"))
        if camera is None:
            lat, lng = entry["centre"]
            camera = [float(lng), float(lat), float(entry["zoom"])]
        cameras[code] = camera
    index = {}
    for zone, iso in sorted(zones.items()):
        code = PROJECT_CODE_FOR_ISO.get(iso, iso)
        if code in cameras:
            index[zone] = code
    return {"zones": index, "cameras": cameras}


def render(table):
    body = json.dumps(table, separators=(",", ":"), ensure_ascii=False)
    return ("// generated by scripts/build_tz_home.py; zone -> project country code,\n"
            "// code -> [lng, lat, zoom]. the global map opens on the visitor's zone\n"
            f"window.POW_TZ_HOME = {body};\n")


def main():
    tab = zone_tab_path()
    zones = parse_zone_tab(tab.read_text(encoding="utf-8"))
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    table = build(registry, zones)
    if table["zones"].get("Pacific/Auckland") != "nz":
        sys.exit(f"{tab} parsed but lacks Pacific/Auckland -> nz; refusing a broken table")
    OUT.write_text(render(table), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(table['zones'])} zones, {len(table['cameras'])} cameras (from {tab})")


if __name__ == "__main__":
    main()
